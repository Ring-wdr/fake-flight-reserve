const panel = (text) => `.panel button:has-text("${text}")`;
let dir = "";
let step = 0;
const shot = async (name) => {
  step++;
  await page.screenshot({ path: `${dir}/${String(step).padStart(2, "0")}-${name}.png` });
};

async function record(site, flow) {
  dir = `${ROOT}/${site}`;
  step = 0;
  const frames = `${dir}/frames`;
  await rm(dir, { recursive: true, force: true });
  await mkdir(frames, { recursive: true });
  await page.goto(SITE_URL);
  await page.evaluate(() => { localStorage.clear(); location.hash = "/"; location.reload(); });
  await pause(1500);
  await page.click(".panel-check input", { label: "turn on annotations" });
  let recording = true;
  let n = 0;
  const stamps = [];
  const recorder = (async () => {
    while (recording) {
      const file = `${frames}/${String(n++).padStart(5, "0")}.png`;
      await page.screenshot({ path: file });
      stamps.push({ file, t: Date.now() });
    }
  })();
  await flow();
  recording = false;
  await recorder;
  const lines = [];
  stamps.forEach((s, i) => {
    const d = i + 1 < stamps.length ? (stamps[i + 1].t - s.t) / 1000 : 2;
    lines.push(`file '${s.file}'`, `duration ${d.toFixed(3)}`);
  });
  lines.push(`file '${stamps[stamps.length - 1].file}'`);
  await writeFile(`${dir}/frames.txt`, lines.join("\n"));
  console.log(site, { frames: n, steps: step });
}

